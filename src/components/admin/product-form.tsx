function ImageField({
  images,
  onChange,
  error,
}: {
  images: string[];
  onChange(next: string[]): void;
  error?: string;
}) {
  const fileRef = useRef<HTMLInputElement>(null);
  const [uploading, setUploading] = useState(false);
  const [uploadError, setUploadError] = useState<string | null>(null);
  const [showLibrary, setShowLibrary] = useState(false);

  async function upload(files: FileList) {
    if (!isSupabaseConfigured) {
      setUploadError("رفع الملفات يحتاج مشروع Supabase — الصقي رابط صورة بدلاً من ذلك.");
      return;
    }

    setUploading(true);
    setUploadError(null);

    try {
      const supabase = createClient();
      const uploaded: string[] = [];

      for (const file of Array.from(files).slice(0, 4)) {
        if (file.size > 5 * 1024 * 1024) {
          throw new Error(`${file.name} أكبر من ٥ ميجابايت`);
        }
        const safeName = file.name.replace(/[^a-zA-Z0-9._-]/g, "-").slice(-60);
        const path = `${crypto.randomUUID()}-${safeName}`;

        const { error } = await supabase.storage
          .from("product-images")
          .upload(path, file, { cacheControl: "31536000", upsert: false });

        if (error) throw error;

        const { data } = supabase.storage.from("product-images").getPublicUrl(path);
        uploaded.push(data.publicUrl);
      }

      onChange([...images, ...uploaded]);
    } catch (caught) {
      setUploadError(caught instanceof Error ? caught.message : "فشل رفع الملف");
    } finally {
      setUploading(false);
      if (fileRef.current) fileRef.current.value = "";
    }
  }

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center gap-2.5">
        <Button
          type="button"
          variant="outline"
          size="sm"
          loading={uploading}
          onClick={() => fileRef.current?.click()}
        >
          <Upload className="size-4" aria-hidden />
          {uploading ? "جارٍ الرفع…" : "رفع صورة"}
        </Button>
        <Button
          type="button"
          variant="ghost"
          size="sm"
          onClick={() => setShowLibrary((open) => !open)}
        >
          <ImagePlus className="size-4" aria-hidden />
          اختيار من المكتبة
        </Button>
        <input
          ref={fileRef}
          type="file"
          accept="image/png,image/jpeg,image/webp,image/avif,image/svg+xml"
          multiple
          hidden
          onChange={(event) => {
            if (event.target.files?.length) void upload(event.target.files);
          }}
        />
      </div>

      {uploadError ? (
        <p role="alert" className="text-[0.78rem] text-rose-800">
          {uploadError}
        </p>
      ) : null}

      {showLibrary ? (
        <div className="rounded-2xl border border-blush-200 bg-white/70 p-3">
          <ul className="grid max-h-56 grid-cols-4 gap-2 overflow-y-auto sm:grid-cols-6">
            {LIBRARY.map((path) => (
              <li key={path}>
                <button
                  type="button"
                  onClick={() => onChange([...images, path])}
                  title={path}
                  className="relative block aspect-square w-full overflow-hidden rounded-xl ring-1 ring-blush-200 transition-all hover:ring-2 hover:ring-rose-400"
                >
                  <Image src={path} alt="" fill sizes="80px" className="object-cover" />
                </button>
              </li>
            ))}
          </ul>
        </div>
      ) : null}

      <ul className="space-y-2.5">
        {images.map((image, index) => (
          <li key={`${image}-${index}`} className="flex items-center gap-3">
            <span className="relative size-12 shrink-0 overflow-hidden rounded-xl bg-cream-200 ring-1 ring-blush-200">
              <Image src={image} alt="" fill sizes="48px" className="object-cover" />
            </span>
            <Input
              value={image}
              onChange={(event) => {
                const next = [...images];
                next[index] = event.target.value;
                onChange(next);
              }}
              aria-label={`رابط الصورة ${index + 1}`}
              dir="ltr"
              className="h-10 text-start text-[0.78rem]"
            />
            <button
              type="button"
              onClick={() => onChange(images.filter((_, i) => i !== index))}
              aria-label={`إزالة الصورة ${index + 1}`}
              className="rounded-full p-2 text-plum-400 transition-colors hover:bg-rose-100 hover:text-rose-800"
            >
              <Trash2 className="size-4" aria-hidden />
            </button>
          </li>
        ))}
      </ul>

      {images.length === 0 ? (
        <p className="text-[0.8rem] text-plum-400">
          لا توجد صور بعد. ارفعي ملفاً، أو اختاري من المكتبة المصوّرة، أو الصقي رابطاً.
        </p>
      ) : null}

      {error ? (
        <p role="alert" className="text-[0.78rem] text-rose-800">
          {error}
        </p>
      ) : null}

      <input type="hidden" name="images" value={JSON.stringify(images)} />
    </div>
  );
}

