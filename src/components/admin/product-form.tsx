function VariantEditor({
  groups,
  onChange,
  error,
}: {
  groups: GroupDraft[];
  onChange(next: GroupDraft[]): void;
  error?: string;
}) {
  function patchGroup(index: number, patch: Partial<GroupDraft>) {
    onChange(groups.map((group, i) => (i === index ? { ...group, ...patch } : group)));
  }

  function patchOption(gi: number, oi: number, patch: Partial<OptionDraft>) {
    onChange(
      groups.map((group, i) =>
        i === gi
          ? {
              ...group,
              options: group.options.map((option, j) =>
                j === oi ? { ...option, ...patch } : option,
              ),
            }
          : group,
      ),
    );
  }

  return (
    <div className="space-y-5">
      {groups.length === 0 ? (
        <p className="text-[0.8rem] text-plum-400">
          لا توجد متغيّرات. هذا مناسب لمنتج بحجم أو درجة واحدة.
        </p>
      ) : null}

      {groups.map((group, gi) => (
        <fieldset
          key={gi}
          className="rounded-3xl border border-blush-200 bg-white/60 p-5"
        >
          <legend className="px-1.5 text-[0.75rem] text-plum-400">
            المجموعة {gi + 1}
          </legend>

          <div className="grid gap-4 sm:grid-cols-3">
            <Field label="العنوان" htmlFor={`g-${gi}-label`} hint="الدرجة، الحجم…">
              <Input
                id={`g-${gi}-label`}
                value={group.label}
                onChange={(event) => patchGroup(gi, { label: event.target.value })}
                className="h-10"
                placeholder="الدرجة"
              />
            </Field>
            <Field label="المفتاح" htmlFor={`g-${gi}-id`} hint="إنجليزي بحروف صغيرة">
              <Input
                id={`g-${gi}-id`}
                value={group.id}
                onChange={(event) => patchGroup(gi, { id: event.target.value })}
                dir="ltr"
                className="h-10 text-start"
                placeholder="shade"
              />
            </Field>
            <Field label="طريقة العرض" htmlFor={`g-${gi}-display`}>
              <Select
                id={`g-${gi}-display`}
                value={group.display}
                onChange={(event) =>
                  patchGroup(gi, {
                    display: event.target.value === "chip" ? "chip" : "swatch",
                  })
                }
                className="h-10"
              >
                <option value="swatch">عيّنات ألوان</option>
                <option value="chip">شرائح نصية</option>
              </Select>
            </Field>
          </div>

          <ul className="mt-5 space-y-2.5">
            {group.options.map((option, oi) => (
              <li
                key={oi}
                className="grid items-center gap-2.5 rounded-2xl bg-cream-100/80 p-3 sm:grid-cols-[auto_1.4fr_1fr_1fr_auto]"
              >
                <GripVertical className="hidden size-4 text-blush-400 sm:block" aria-hidden />

                <Input
                  value={option.name}
                  onChange={(event) => patchOption(gi, oi, { name: event.target.value })}
                  aria-label="اسم الخيار"
                  placeholder="فيلفت نوار"
                  className="h-9 text-[0.82rem]"
                />

                {group.display === "swatch" ? (
                  <div className="flex items-center gap-2">
                    <input
                      type="color"
                      value={option.hex || "#B76E79"}
                      onChange={(event) => patchOption(gi, oi, { hex: event.target.value })}
                      aria-label="لون العيّنة"
                      className="h-9 w-11 cursor-pointer rounded-lg border border-blush-200 bg-white"
                    />
                    <Input
                      value={option.hex}
                      onChange={(event) => patchOption(gi, oi, { hex: event.target.value })}
                      aria-label="كود اللون"
                      dir="ltr"
                      className="h-9 text-start text-[0.75rem]"
                      placeholder="#B76E79"
                    />
                  </div>
                ) : (
                  <Input
                    value={option.caption}
                    onChange={(event) =>
                      patchOption(gi, oi, { caption: event.target.value })
                    }
                    aria-label="وصف الخيار"
                    className="h-9 text-[0.82rem]"
                    placeholder="50 مل"
                  />
                )}

                <div className="flex gap-2">
                  <Input
                    value={option.priceDelta}
                    onChange={(event) =>
                      patchOption(gi, oi, { priceDelta: event.target.value })
                    }
                    aria-label="فرق السعر"
                    type="number"
                    dir="ltr"
                    className="h-9 text-start text-[0.78rem]"
                    placeholder="+0"
                  />
                  <Input
                    value={option.stock}
                    onChange={(event) => patchOption(gi, oi, { stock: event.target.value })}
                    aria-label="مخزون الخيار"
                    type="number"
                    min={0}
                    dir="ltr"
                    className="h-9 text-start text-[0.78rem]"
                    placeholder="0"
                  />
                </div>

                <button
                  type="button"
                  disabled={group.options.length <= 1}
                  onClick={() =>
                    patchGroup(gi, {
                      options: group.options.filter((_, j) => j !== oi),
                    })
                  }
                  aria-label="إزالة الخيار"
                  className="rounded-full p-2 text-plum-400 transition-colors hover:bg-rose-100 hover:text-rose-800 disabled:opacity-30"
                >
                  <X className="size-4" aria-hidden />
                </button>
              </li>
            ))}
          </ul>

          <div className="mt-4 flex flex-wrap gap-2">
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => patchGroup(gi, { options: [...group.options, emptyOption()] })}
            >
              <Plus className="size-3.5" aria-hidden />
              إضافة خيار
            </Button>
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => onChange(groups.filter((_, i) => i !== gi))}
              className="text-rose-700 hover:bg-rose-100"
            >
              <Trash2 className="size-3.5" aria-hidden />
              حذف المجموعة
            </Button>
          </div>
        </fieldset>
      ))}

      <div className="flex flex-wrap gap-2">
        <Button
          type="button"
          variant="outline"
          size="sm"
          onClick={() => onChange([...groups, emptyGroup()])}
        >
          <Plus className="size-4" aria-hidden />
          إضافة مجموعة متغيّرات
        </Button>
        <Button
          type="button"
          variant="ghost"
          size="sm"
          onClick={() =>
            onChange([
              ...groups,
              { id: "size", label: "الحجم", display: "chip", options: [emptyOption()] },
            ])
          }
        >
          إضافة مجموعة أحجام
        </Button>
      </div>

      {error ? (
        <p role="alert" className="text-[0.78rem] text-rose-800">
          {error}
        </p>
      ) : null}

      <input
        type="hidden"
        name="variant_groups"
        value={JSON.stringify(serialiseGroups(groups))}
      />
    </div>
  );
}

