function serialiseGroups(groups: GroupDraft[]) {
  return groups
    .map((group) => ({
      id: slugify(group.id || group.label) || "option",
      label: group.label.trim(),
      display: group.display,
      options: group.options
        .map((option) => {
          const name = option.name.trim();
          if (!name) return null;
          return {
            id: slugify(option.id || name) || "option",
            name,
            ...(group.display === "swatch" && option.hex ? { hex: option.hex } : {}),
            ...(option.priceDelta.trim() !== ""
              ? { priceDelta: Number(option.priceDelta) }
              : {}),
            ...(option.stock.trim() !== "" ? { stock: Number(option.stock) } : {}),
            ...(option.image.trim() !== "" ? { image: option.image.trim() } : {}),
            ...(option.caption.trim() !== "" ? { caption: option.caption.trim() } : {}),
          };
        })
        .filter((option): option is NonNullable<typeof option> => option !== null),
    }))
    .filter((group) => group.options.length > 0);
}

